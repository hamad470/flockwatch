"""
Create a synthetic labelled training set in the SAME folder layout as the public dataset:
    data/raw/healthy/*.wav, data/raw/unhealthy/*.wav, data/raw/noise/*.wav
plus data/raw/metadata.csv (recording session, house, device, timestamp, provenance).

To use real recordings instead, delete data/raw and copy the real dataset folders in,
then run `python -m flockwatch.train`.
"""
from __future__ import annotations
import argparse
import numpy as np
import pandas as pd
from .config import RAW, CLASSES
from .audio_synth import make_clip
from .features import save_wav


def main(n_sessions: int = 120, clips_per_session: int = 10, seed: int = 7):
    rng = np.random.default_rng(seed)
    rows = []
    for c in CLASSES:
        (RAW / c).mkdir(parents=True, exist_ok=True)
    for s in range(n_sessions):
        label = CLASSES[s % len(CLASSES)]
        house = f"H{rng.integers(1, 9)}"
        device = f"MIC-{house}-{rng.integers(1, 4)}"
        day = pd.Timestamp("2026-01-05") + pd.Timedelta(days=int(rng.integers(0, 120)))
        severity = rng.uniform(0.3, 1.0)
        for k in range(clips_per_session):
            clip_id = f"S{s:03d}_{k:02d}"
            x = make_clip(label, rng, severity=severity)
            path = RAW / label / f"{clip_id}.wav"
            save_wav(path, x)
            rows.append({
                "clip_id": clip_id, "path": str(path.relative_to(RAW)), "label": label,
                "session_id": f"S{s:03d}", "house_id": house, "device_id": device,
                "recorded_at": (day + pd.Timedelta(minutes=10 * k)).isoformat(),
                "source": "synthetic", "licence": "CC BY 4.0 (synthetic, generated by this repo)",
            })
    meta = pd.DataFrame(rows)
    meta.to_csv(RAW / "metadata.csv", index=False)
    print(meta.label.value_counts().to_dict(), "sessions:", n_sessions)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--sessions", type=int, default=120)
    ap.add_argument("--clips", type=int, default=10)
    a = ap.parse_args()
    main(a.sessions, a.clips)
